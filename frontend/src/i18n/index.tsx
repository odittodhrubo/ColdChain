const TABLES: Record<Lang, Partial<Record<StringKey, string>>> = { en, bn };
const STORAGE_KEY = 'coldchain.lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'bn') return saved;
  } catch {
    /* storage blocked */
  }
  try {
    if (navigator.language.toLowerCase().startsWith('bn')) return 'bn';
  } catch {
    /* no navigator */
  }
  return 'en';
}

interface I18n {
  lang: Lang;
  setLang(l: Lang): void;
  t(key: StringKey): string;
}

const Ctx = createContext<I18n | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage blocked: the choice still holds for this view */
    }
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<I18n>(
    () => ({ lang, setLang, t: (key) => TABLES[lang][key] ?? en[key] ?? key }),
    [lang, setLang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

// Outside a LanguageProvider (isolated component tests, or a render before the provider mounts) fall back to
// English rather than throwing, so a missing provider never crashes a screen.
const FALLBACK: I18n = { lang: 'en', setLang: () => undefined, t: (key) => en[key] ?? key };

export function useT(): I18n {
  return useContext(Ctx) ?? FALLBACK;
}

/** Fill {name} placeholders in a translated string: fmt(t('x.y'), { n: 3 }). */
export const fmt = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_m, k) => String(vars[k] ?? ''));
