#!/usr/bin/env node
// Write firmware/fridge-node/include/config.h (git-ignored) from .env, so the firmware, backend and virtual node
// share one set of device secrets and broker settings.
//   node tools/init_firmware_config.js           refuses to overwrite an existing config.h
//   node tools/init_firmware_config.js --force
// Missing DEVICE_SECRET_FRIDGE_01/02 are generated and appended to .env first.
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const target = path.join(root, 'firmware', 'fridge-node', 'include', 'config.h');
const DEVICES = ['fridge-01', 'fridge-02'];
const secretVar = (id) => `DEVICE_SECRET_${id.replace(/-/g, '_').toUpperCase()}`;

if (!fs.existsSync(envPath)) {
  console.error('.env not found: run `npm run env:init` first.');
  process.exit(1);
}
if (fs.existsSync(target) && !process.argv.includes('--force')) {
  console.error(`${path.relative(root, target)} already exists; pass --force to overwrite it.`);
  process.exit(1);
}

const parse = (text) =>
  Object.fromEntries(
    text
      .split(/\r?\n/)
      .filter((l) => /^[A-Z0-9_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()]),
  );

let env = parse(fs.readFileSync(envPath, 'utf8'));
const missing = DEVICES.map(secretVar).filter((k) => !/^[0-9a-f]{64}$/.test(env[k] ?? ''));
if (missing.length) {
  const lines = missing.map((k) => `${k}=${crypto.randomBytes(32).toString('hex')}`);
  fs.appendFileSync(
    envPath,
    `\n# device secrets (generated by tools/init_firmware_config.js)\n${lines.join('\n')}\n`,
  );
  console.log(`appended ${missing.join(', ')} to .env`);
  env = parse(fs.readFileSync(envPath, 'utf8'));
}

const url = new URL(env.MQTT_URL || 'mqtt://broker.hivemq.com:1883');
const tls = url.protocol === 'mqtts:';
const port = Number(url.port || (tls ? 8883 : 1883));
const cstr = (s) => JSON.stringify(s ?? '');

const config = `// GENERATED by tools/init_firmware_config.js from .env. Git-ignored: holds real device secrets.
#pragma once

#define WIFI_SSID "Wokwi-GUEST"
#define WIFI_PASS ""
#define NTP_SERVER "pool.ntp.org"

#define MQTT_HOST ${cstr(url.hostname)}
#define MQTT_PORT ${port}
#define MQTT_TLS ${tls ? 1 : 0}
#define MQTT_USER ${cstr(env.MQTT_USERNAME)}
#define MQTT_PASS ${cstr(env.MQTT_PASSWORD)}
#define MQTT_TOPIC_PREFIX ${cstr(env.MQTT_TOPIC_PREFIX || 'coldchain/v1')}

// Simulation only: real deployments remove this and define MQTT_CA_CERT (see config.example.h).
#define ALLOW_INSECURE_TLS

#define DEVICE_SECRETS \\
  { \\
${DEVICES.map((id) => `    {"${id}", "${env[secretVar(id)]}"}, \\`).join('\n')}
  }
`;

fs.writeFileSync(target, config);
console.log(`wrote ${path.relative(root, target)} (${url.hostname}:${port}, ${tls ? 'TLS' : 'plain'})`);
