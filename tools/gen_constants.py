#!/usr/bin/env python3
"""Generate per-language constants from contracts/constants.json.

python tools/gen_constants.py          # write the three generated files
python tools/gen_constants.py --check  # exit 1 if any generated file is stale
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "contracts" / "constants.json"
HEADER = "AUTO-GENERATED by tools/gen_constants.py from contracts/constants.json. DO NOT EDIT."


def load() -> tuple[dict, dict]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    topics = data.pop("TOPICS")
    scalars = {k: v for k, v in data.items() if not k.startswith("_")}
    for k, v in scalars.items():
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            raise SystemExit(f"constants.json: {k} must be a number, got {v!r}")
    return scalars, topics


def num(v: int | float) -> str:
    return repr(float(v)) if isinstance(v, float) else str(v)


def render_cpp(scalars: dict, topics: dict) -> str:
    lines = [f"// {HEADER}", "#pragma once", "#include <stdint.h>", "", "namespace cc {", ""]
    for k, v in scalars.items():
        if isinstance(v, float):
            lines.append(f"constexpr float {k} = {num(v)}f;")
        else:
            lines.append(f"constexpr uint32_t {k} = {v};")
    lines.append("")
    for name, tpl in topics.items():
        lines.append(f'constexpr const char* TOPIC_{name.upper()} = "{tpl}";')
    lines += ["", "}  // namespace cc", ""]
    return "\n".join(lines)


def render_ts(scalars: dict, topics: dict) -> str:
    lines = [f"// {HEADER}", ""]
    for k, v in scalars.items():
        lines.append(f"export const {k} = {num(v)};")
    lines += ["", "export const TOPICS = {"]
    for name, tpl in topics.items():
        lines.append(f"  {name}: '{tpl}',")
    lines += ["} as const;", "", "export type TopicKind = keyof typeof TOPICS;", ""]
    return "\n".join(lines)


def render_py(scalars: dict, topics: dict) -> str:
    lines = [f'"""{HEADER}"""', ""]
    for k, v in scalars.items():
        lines.append(f"{k} = {num(v)}")
    lines += ["", "TOPICS = {"]
    for name, tpl in topics.items():
        lines.append(f'    "{name}": "{tpl}",')
    lines += ["}", ""]
    return "\n".join(lines)


TARGETS = {
    ROOT / "firmware" / "fridge-node" / "include" / "constants.h": render_cpp,
    ROOT / "backend" / "src" / "shared" / "constants.ts": render_ts,
    ROOT / "frontend" / "src" / "lib" / "constants.ts": render_ts,
    ROOT / "ml" / "constants.py": render_py,
}


def main() -> int:
    check = "--check" in sys.argv[1:]
    scalars, topics = load()
    stale = []
    for path, render in TARGETS.items():
        content = render(scalars, topics)
        rel = path.relative_to(ROOT).as_posix()
        if check:
            current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
            if current != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if stale:
        print("STALE generated constants (run `python tools/gen_constants.py`):", *stale, sep="\n  ")
        return 1
    if check:
        print("generated constants are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
