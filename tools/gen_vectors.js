#!/usr/bin/env node
// Generate contracts/test_vectors.json with real values computed by code.
//   node tools/gen_vectors.js          write the file
//   node tools/gen_vectors.js --check  exit 1 if the file is stale
// Every implementation (firmware, backend, virtual node) must pass these vectors.
'use strict';

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'contracts', 'test_vectors.json');
const C = JSON.parse(fs.readFileSync(path.join(ROOT, 'contracts', 'constants.json'), 'utf8'));

// ---- reference implementations (Part 3.2 / 3.4) ----

function signingString({ device_id, kind, ts, nonce, body }) {
  return `${device_id}|${kind}|${ts}|${nonce}|${body}`;
}

// Key = UTF-8 bytes of the secret string exactly as stored (the 64-char hex text, not decoded).
function sign(secret, fields) {
  return crypto.createHmac('sha256', Buffer.from(secret, 'utf8')).update(signingString(fields), 'utf8').digest('hex');
}

function classify(temp, door, power, sensorFault) {
  if (sensorFault || temp > C.SAFE_MAX_C || temp < C.SAFE_MIN_C) return 'BREACH';
  if ((temp > C.WARN_HIGH_C && temp <= C.SAFE_MAX_C) || (temp >= C.SAFE_MIN_C && temp < C.WARN_LOW_C)) return 'WARNING';
  if (door === 1 || power === 'BATTERY') return 'WARNING';
  return 'SAFE';
}

function weight(temp) {
  if (temp > C.DOUBLE_ABOVE_C) return 2;
  if (temp > C.SAFE_MAX_C) return 1;
  return 0;
}

function weightedSeconds(samples) {
  return samples.reduce((acc, [dt, temp]) => acc + dt * weight(temp), 0);
}

function remainingPct(weighted) {
  return Math.max(0, 100 * (1 - weighted / C.BUDGET_S));
}

// ---- inputs ----

const testSecret = (n) => crypto.createHash('sha256').update(`coldchain-test-secret-${n}`).digest('hex');
const body = (o) => JSON.stringify(o);

const hmacInputs = [
  {
    name: 'telemetry periodic',
    device_id: 'fridge-01', kind: 'telemetry', ts: 1767225600, nonce: '9f2c1a7b5d3e4f60',
    body: body({ seq: 1204, ts: 1767225600, temp: 4.62, door: 0, comp: 1, power: 'MAINS', batt: 100, state: 'SAFE', exp_s: 0, latch: 0, mode: 'model', buf: 0, rssi: -58, fw: '1.0.0', reason: 'periodic' }),
  },
  {
    name: 'event door open',
    device_id: 'fridge-02', kind: 'event', ts: 1767225605, nonce: '0123456789abcdef',
    body: body({ seq: 88, ts: 1767225604, type: 'DOOR_OPEN', data: {} }),
  },
  {
    name: 'sync chunk',
    device_id: 'fridge-01', kind: 'sync', ts: 1767229200, nonce: 'a1b2c3d4e5f60718',
    body: body({
      from_seq: 1300, to_seq: 1301,
      readings: [
        { seq: 1300, ts: 1767228000, temp: 8.4, door: 1, comp: 0, power: 'BATTERY', batt: 92, state: 'BREACH', exp_s: 30, latch: 0, mode: 'model', reason: 'periodic' },
        { seq: 1301, ts: 1767228005, temp: 8.6, door: 1, comp: 0, power: 'BATTERY', batt: 92, state: 'BREACH', exp_s: 35, latch: 0, mode: 'model', reason: 'periodic' },
      ],
    }),
  },
  {
    name: 'server ack',
    device_id: 'fridge-01', kind: 'ack', ts: 1767229201, nonce: 'ffeeddccbbaa9988',
    body: body({ seq_upto: 1301 }),
  },
  {
    name: 'server cmd reset latch',
    device_id: 'fridge-02', kind: 'cmd', ts: 1767230000, nonce: '5a5a5a5a00000001',
    body: body({ cmd_id: '3f1d2c4b-8e7a-4b6c-9d0e-1f2a3b4c5d6e', type: 'RESET_LATCH', args: {} }),
  },
];

const statusInputs = [
  [5.0, 0, 'MAINS', false],
  [2.5, 0, 'MAINS', false],
  [7.5, 0, 'MAINS', false],
  [7.51, 0, 'MAINS', false],
  [8.0, 0, 'MAINS', false],
  [8.01, 0, 'MAINS', false],
  [2.0, 0, 'MAINS', false],
  [1.99, 0, 'MAINS', false],
  [5.0, 1, 'MAINS', false],
  [5.0, 0, 'BATTERY', false],
  [9.0, 1, 'BATTERY', false],
  [5.0, 0, 'MAINS', true],
];

const exposureInputs = [
  ['all safe', [[600, 5.0], [600, 7.9]]],
  ['exactly 8.0 does not count', [[300, 8.0]]],
  ['60 s at 9 C counts x1', [[60, 9.0]]],
  ['60 s at 13 C counts x2', [[60, 13.0]]],
  ['exactly 12.0 counts x1', [[100, 12.0]]],
  ['mixed excursion', [[30, 6.0], [120, 8.5], [45, 12.5], [60, 10.0], [30, 4.0]]],
  ['crosses into at-risk', [[1500, 13.0]]],
  ['budget exhausted', [[2000, 13.0]]],
];

// ---- build ----

const vectors = {
  _comment: 'AUTO-GENERATED by tools/gen_vectors.js. DO NOT EDIT. HMAC key = UTF-8 bytes of the secret string as stored.',
  hmac: hmacInputs.map((v, i) => {
    const secret = testSecret(i + 1);
    return { ...v, secret, signing_string: signingString(v), sig: sign(secret, v) };
  }),
  status: statusInputs.map(([temp, door, power, sensor_fault]) => ({
    temp, door, power, sensor_fault, expected: classify(temp, door, power, sensor_fault),
  })),
  exposure: exposureInputs.map(([name, samples]) => {
    const w = weightedSeconds(samples);
    return { name, samples, expected_weighted_s: w, expected_remaining_pct: Number(remainingPct(w).toFixed(4)) };
  }),
};

// ---- self-check against values stated in the spec ----

assert.equal(vectors.hmac.length, 5);
assert.equal(vectors.status.length, 12);
assert.equal(vectors.exposure.length, 8);
assert.equal(classify(8.0, 0, 'MAINS', false), 'WARNING');
assert.equal(classify(8.01, 0, 'MAINS', false), 'BREACH');
assert.equal(classify(2.0, 0, 'MAINS', false), 'WARNING');
assert.equal(classify(7.5, 0, 'MAINS', false), 'SAFE');
assert.equal(weightedSeconds([[60, 9]]), 60);
assert.equal(weightedSeconds([[60, 13]]), 120);
assert.equal(weightedSeconds([[30, 13]]), 60);
assert.equal(remainingPct(3600), 0);
for (const v of vectors.hmac) assert.match(v.sig, /^[0-9a-f]{64}$/);

// Firmware native tests cannot parse JSON, so the vectors they need are also emitted as a C++ header.
const HEADER_OUT = path.join(ROOT, 'firmware', 'fridge-node', 'include', 'test_vectors.h');
const cppFloat = (x) => (Number.isInteger(x) ? x.toFixed(1) : String(x)) + 'f';
const header = [
  '// AUTO-GENERATED by tools/gen_vectors.js (same data as contracts/test_vectors.json). DO NOT EDIT.',
  '#pragma once',
  '#include <stddef.h>',
  '',
  'namespace vectors {',
  '',
  'struct StatusVector {',
  '  float temp;',
  '  bool door_open;',
  '  bool on_battery;',
  '  bool sensor_fault;',
  '  const char* expected;',
  '};',
  '',
  'constexpr StatusVector STATUS[] = {',
  ...vectors.status.map(
    (v) => `    {${cppFloat(v.temp)}, ${v.door === 1}, ${v.power === 'BATTERY'}, ${v.sensor_fault}, "${v.expected}"},`,
  ),
  '};',
  'constexpr size_t STATUS_COUNT = sizeof(STATUS) / sizeof(STATUS[0]);',
  '',
  '}  // namespace vectors',
  '',
].join('\n');

const outputs = [
  [OUT, JSON.stringify(vectors, null, 2) + '\n'],
  [HEADER_OUT, header],
];

if (process.argv.includes('--check')) {
  const stale = outputs.filter(
    ([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== content,
  );
  for (const [file] of stale) console.error(`STALE ${path.relative(ROOT, file)} (run \`node tools/gen_vectors.js\`)`);
  if (stale.length) process.exit(1);
  console.log('test vectors are up to date');
} else {
  for (const [file, content] of outputs) {
    fs.writeFileSync(file, content);
    console.log(`wrote ${path.relative(ROOT, file)}`);
  }
}
